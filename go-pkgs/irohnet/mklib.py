#!/usr/bin/env python3
"""Build the irohnet-ffi Rust staticlib and stage it where the cgo
directives expect it (clib/<archdir>/libirohnet_ffi.a).

    ./mklib.py            # host (darwin): cargo build --release -> clib/darwin/
    ./mklib.py arm        # device (armv7 musl, the BQ268)     -> clib/linux_arm/

clib/ is a build artifact (gitignored); re-run to regenerate. The iroh
version is pinned by rust/Cargo.lock (committed) — every build is --locked.

The arm cross-build needs rustup (for the armv7-unknown-linux-musleabihf
std, installed on first run) and zig (the C cross-toolchain the audio
module's mklibs.sh already uses — ring's C sources ride it here). cargo and
rustc are resolved through `rustup which` rather than PATH: a distro rustc
earlier on PATH has no cross std, and `rustup run` does not reliably win the
PATH race. cc-rs passes clang-style `--target=<triple>` flags that zig
rejects (zig names the arch `arm`, not `armv7`), so the generated cc wrapper
strips them and pins zig's own `-target`.

NB (same trap as go-pkgs/audio): Go's build cache does not see .a changes —
after rebuilding the lib, build the consuming binary with `go build -a` or
clean the cache.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUST = HERE / "rust"

RUST_TARGET = "armv7-unknown-linux-musleabihf"
ZIG_TARGET = "arm-linux-musleabihf"

CC_WRAPPER = """#!/bin/sh
# Generated by mklib.py: zig as the armv7-musl cross cc for cargo's C deps.
# Drop clang-style --target= (zig's arch spelling differs); zig -target rules.
args=""
for a in "$@"; do
  case "$a" in --target=*) ;; *) args="$args \\"$a\\"" ;; esac
done
eval exec zig cc -target {zig_target} $args
"""

AR_WRAPPER = """#!/bin/sh
# Generated by mklib.py: zig's llvm-ar for the cross archive steps.
exec zig ar "$@"
"""


def rustup_which(tool: str) -> str:
    r = subprocess.run(["rustup", "which", tool], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"[mklib] rustup which {tool} failed (rustup required for the arm cross-build): {r.stderr.strip()}")
    return r.stdout.strip()


def build_host() -> Path:
    subprocess.run(["cargo", "build", "--release", "--locked"], cwd=RUST, check=True)
    return RUST / "target" / "release" / "libirohnet_ffi.a"


def build_arm() -> Path:
    if shutil.which("zig") is None:
        sys.exit("[mklib] zig not installed (the C cross-toolchain; ring's C sources need it)")
    cargo = rustup_which("cargo")
    rustc = rustup_which("rustc")
    installed = subprocess.run(
        ["rustup", "target", "list", "--installed"], capture_output=True, text=True, check=True
    ).stdout.split()
    if RUST_TARGET not in installed:
        subprocess.run(["rustup", "target", "add", RUST_TARGET], check=True)
    tooldir = HERE / "clib" / "cross-tools"
    tooldir.mkdir(parents=True, exist_ok=True)
    cc = tooldir / "cc-arm"
    ar = tooldir / "ar-arm"
    cc.write_text(CC_WRAPPER.format(zig_target=ZIG_TARGET))
    ar.write_text(AR_WRAPPER)
    cc.chmod(0o755)
    ar.chmod(0o755)
    env_target = RUST_TARGET.replace("-", "_")
    env = {
        **os.environ,
        "RUSTC": rustc,
        f"CC_{env_target}": str(cc),
        f"AR_{env_target}": str(ar),
    }
    subprocess.run(
        [cargo, "build", "--release", "--locked", "--target", RUST_TARGET],
        cwd=RUST, env=env, check=True,
    )
    return RUST / "target" / RUST_TARGET / "release" / "libirohnet_ffi.a"


def main() -> int:
    arch = sys.argv[1] if len(sys.argv) > 1 else "host"
    if arch == "host":
        lib, archdir = build_host(), "darwin"
    elif arch == "arm":
        lib, archdir = build_arm(), "linux_arm"
    else:
        sys.exit(f"[mklib] unknown arch {arch!r} (want: host | arm)")
    out = HERE / "clib" / archdir
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy2(lib, out / lib.name)
    size_mb = lib.stat().st_size / (1024 * 1024)
    print(f"[mklib] {out / lib.name} ({size_mb:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
