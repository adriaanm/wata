/** The RGB565 draw layer: framebuffer primitives and a 5x8 bitmap font (no
 *  vector/TrueType font support). Device-layer app code (wata-fb).
 *
 *  The pixel buffer is a `go.Bytes` (RGB565 LITTLE-ENDIAN, W*H*2 bytes) so the
 *  device backend's present() is a byte memcpy into the mmap'd /dev/fb0 (the
 *  fb IS 160x128x2 = 40960 bytes, direct blit) and the host PNG export reads
 *  it directly. NO class holds the buffer — the subset forbids plain
 *  non-case classes AND a `go.Bytes` field in a case class is a known
 *  landmine, so draw ops are `object` functions over a passed buffer, in
 *  keeping with the rest of this codebase's object-oriented-free style.
 *
 *  Geometry is FIXED at 160x128; there is no ioctl geometry discovery. */
object Display:
  val W: scala.Int = 160
  val H: scala.Int = 128
  val BYTES: scala.Int = W * H * 2   // 40960 — one RGB565 frame

/** RGB565 colors — the ST7735S hardware format. Named values are
 *  precomputed literals (rgb() is kept for dynamic use). */
object Color:
  def rgb(r: scala.Int, g: scala.Int, b: scala.Int): scala.Int =
    ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
  val black: scala.Int     = 0x0000
  val white: scala.Int     = 0xffff
  val green: scala.Int     = 0x07e0   // rgb(0,255,0)
  val red: scala.Int       = 0xf800   // rgb(255,0,0)
  val blue: scala.Int      = 0x001f   // rgb(0,0,255)
  val cyan: scala.Int      = 0x07ff   // rgb(0,255,255)
  val yellow: scala.Int    = 0xffe0   // rgb(255,255,0)
  val orange: scala.Int    = 0xfd20   // rgb(255,165,0)
  val darkGreen: scala.Int = 0x05a0   // rgb(0,180,0)
  val darkGray: scala.Int  = 0x2945   // rgb(40,40,40)
  val midGray: scala.Int   = 0x632c   // rgb(100,100,100)

/** the pixel-buffer draw primitives. */
object Draw:
  def newBuffer(): go.Bytes =
    // NB `go.makeSlice` maps to `make([]T,n)` only in val/statement position,
    // not in tail/return position — an emitter sharp edge to keep in mind.
    val b = go.makeSlice[Byte](Display.BYTES)
    b

  def setPixel(px: go.Bytes, x: scala.Int, y: scala.Int, color: scala.Int): Unit =
    if x < 0 || y < 0 || x >= Display.W || y >= Display.H then ()
    else
      val idx = (y * Display.W + x) * 2
      px(idx) = (color & 0xff).toByte
      px(idx + 1) = ((color >> 8) & 0xff).toByte

  def clear(px: go.Bytes, color: scala.Int): Unit =
    val lo = (color & 0xff).toByte
    val hi = ((color >> 8) & 0xff).toByte
    var i = 0
    val n = Display.BYTES
    while i < n do
      px(i) = lo
      px(i + 1) = hi
      i = i + 2

  def fillRect(px: go.Bytes, x: scala.Int, y: scala.Int, w: scala.Int, h: scala.Int, color: scala.Int): Unit =
    var dy = 0
    while dy < h do
      val py = y + dy
      if py < 0 || py >= Display.H then ()
      else
        var dx = 0
        while dx < w do
          val cx = x + dx
          if cx < 0 || cx >= Display.W then ()
          else
            val idx = (py * Display.W + cx) * 2
            px(idx) = (color & 0xff).toByte
            px(idx + 1) = ((color >> 8) & 0xff).toByte
          dx = dx + 1
      dy = dy + 1

  def hline(px: go.Bytes, x: scala.Int, y: scala.Int, w: scala.Int, color: scala.Int): Unit =
    fillRect(px, x, y, w, 1, color)

  /** 1px border rectangle (not filled). */
  def strokeRect(px: go.Bytes, x: scala.Int, y: scala.Int, w: scala.Int, h: scala.Int, color: scala.Int): Unit =
    hline(px, x, y, w, color)
    hline(px, x, y + h - 1, w, color)
    fillRect(px, x, y, 1, h, color)
    fillRect(px, x + w - 1, y, 1, h, color)

