  /** draw one glyph `code` (0..255) at pixel (px0, py0). */
  def drawChar(px: go.Bytes, code: scala.Int, px0: scala.Int, py0: scala.Int, fg: scala.Int, hasBg: Boolean, bg: scala.Int): Unit =
    val base = (code & 0xff) * 8
    var row = 0
    while row < GLYPH_H do
      val bits = glyphs(base + row)
      var col = 0
      while col < GLYPH_DATA_W do
        val on = ((bits >> (7 - col)) & 1) == 1
        if on then Draw.setPixel(px, px0 + col, py0 + row, fg)
        else if hasBg then Draw.setPixel(px, px0 + col, py0 + row, bg)
        col = col + 1
      // spacing column: background only
      if hasBg then Draw.setPixel(px, px0 + GLYPH_DATA_W, py0 + row, bg)
      row = row + 1

  /** draw an ASCII string at char grid (col, row); row 0 starts at y=1 (below
   *  the 1px status line). Uses the byte view (ASCII). */
  def drawText(px: go.Bytes, text: String, col: scala.Int, row: scala.Int, fg: scala.Int, hasBg: Boolean, bg: scala.Int): Unit =
    val bs = go.bytes(text)
    var i = 0
    var going = true
    while going && i < bs.length do
      val x = (col + i) * GLYPH_W
      val y = 1 + row * GLYPH_H
      if x + GLYPH_W > Display.W then going = false
      else
        drawChar(px, bs(i).toInt & 0xff, x, y, fg, hasBg, bg)
        i = i + 1

  def drawTextCentered(px: go.Bytes, text: String, row: scala.Int, fg: scala.Int, hasBg: Boolean, bg: scala.Int): Unit =
    val nchars = go.bytes(text).length
    val col = if nchars >= COLS then 0 else (COLS - nchars) / 2
    drawText(px, text, col, row, fg, hasBg, bg)
